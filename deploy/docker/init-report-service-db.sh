#!/bin/sh
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
DO \$\$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${REPORT_DB_APP_USER:-report_service}') THEN
        CREATE ROLE ${REPORT_DB_APP_USER:-report_service}
            WITH LOGIN PASSWORD '${REPORT_DB_APP_PASSWORD:-reportsecret}';
    END IF;
END
\$\$;

GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${REPORT_DB_APP_USER:-report_service};
GRANT USAGE, CREATE ON SCHEMA public TO ${REPORT_DB_APP_USER:-report_service};
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ${REPORT_DB_APP_USER:-report_service};
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO ${REPORT_DB_APP_USER:-report_service};
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${REPORT_DB_APP_USER:-report_service};
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO ${REPORT_DB_APP_USER:-report_service};
SQL
